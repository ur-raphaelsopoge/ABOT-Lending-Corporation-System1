alter table public.users
    add column if not exists credits numeric(12, 2) not null default 0
        check (credits >= 0),
    add column if not exists balance_owed numeric(12, 2) not null default 0
        check (balance_owed >= 0);

alter table public.loan_applications
    add column if not exists outstanding_balance numeric(12, 2)
        check (outstanding_balance is null or outstanding_balance >= 0),
    add column if not exists repayment_status varchar(20)
        check (repayment_status is null or repayment_status in ('active', 'paid'));

update public.loan_applications
set outstanding_balance = coalesce(total_payable, amount),
    repayment_status = 'active'
where status = 'approved'
  and (repayment_status is null or outstanding_balance is null);

update public.users u
set credits = coalesce((
        select sum(coalesce(la.approved_amount, la.amount))
        from public.loan_applications la
        where la.user_id = u.id and la.status = 'approved'
    ), 0),
    balance_owed = coalesce((
        select sum(coalesce(la.outstanding_balance, 0))
        from public.loan_applications la
        where la.user_id = u.id and la.repayment_status = 'active'
    ), 0);

create sequence if not exists public.loan_payment_seq start with 1 increment by 1;

create table if not exists public.loan_payments (
    id bigint generated by default as identity primary key,
    payment_number varchar(20) not null
        default ('PAY-' || lpad(nextval('public.loan_payment_seq')::text, 6, '0')),
    loan_application_id bigint not null references public.loan_applications (id) on delete restrict,
    user_id bigint not null references public.users (id) on delete restrict,
    reference_number varchar(80) not null,
    amount numeric(12, 2) not null check (amount > 0),
    payment_method varchar(30) not null default 'gcash'
        check (payment_method in ('cash', 'gcash', 'bank_transfer', 'other')),
    status varchar(20) not null default 'pending'
        check (status in ('pending', 'confirmed', 'rejected')),
    notes text,
    confirmed_by bigint references public.admins (id) on delete set null,
    confirmed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint loan_payments_number_unique unique (payment_number)
);

create index if not exists loan_payments_user_id_idx on public.loan_payments (user_id);
create index if not exists loan_payments_loan_application_id_idx on public.loan_payments (loan_application_id);
create index if not exists loan_payments_status_idx on public.loan_payments (status);
create index if not exists loan_payments_created_at_idx on public.loan_payments (created_at desc);

alter table public.loan_payments enable row level security;

drop table if exists public.receipt_logs cascade;
drop table if exists public.capital_shares cascade;
